def load_key():
    return open(".secret.key", "rb").read()

def decrypt_message(encrypted_message):
    key = load_key()
    f = Fernet(key)
    decrypted_message = f.decrypt(encrypted_message.encode()).decode()
    return decrypted_message

def get_config_decrypt(key, default=''):
    """Si el valor en .env está encriptado lo desencripta; si está vacío o en claro, lo devuelve tal cual."""
    raw = config(key, default=default)
    if not raw:
        return default
    try:
        return decrypt_message(raw)
    except InvalidToken:
        return raw


